"""Freqtrade configuration generator.

Generates freqtrade-compatible JSON config from our AppConfig,
handling exchange mapping, pair lists, and strategy settings.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

from trading_bot.config import AppConfig

logger = logging.getLogger(__name__)

# Map our Binance-style symbols to Freqtrade pair format
SYMBOL_TO_PAIR: dict[str, str] = {
    "BTCUSDT": "BTC/USDT",
    "ETHUSDT": "ETH/USDT",
    "SOLUSDT": "SOL/USDT",
    "ADAUSDT": "ADA/USDT",
    "DOTUSDT": "DOT/USDT",
    "LINKUSDT": "LINK/USDT",
    "AVAXUSDT": "AVAX/USDT",
    "MATICUSDT": "MATIC/USDT",
}


def generate_freqtrade_config(
    app_config: AppConfig,
    *,
    exchange: str = "binance",
    dry_run: bool = True,
    output_path: Path | None = None,
) -> dict[str, Any]:
    """Generate a Freqtrade-compatible configuration dict.

    Args:
        app_config: Our application config.
        exchange: Exchange name for Freqtrade (binance, coinbasepro, etc.).
        dry_run: Whether to run in paper mode.
        output_path: If provided, writes config to this JSON file.

    Returns:
        Freqtrade configuration dict.
    """
    # Convert our symbols to Freqtrade pair format
    pairs = []
    for symbol in app_config.crypto.symbols:
        pair = SYMBOL_TO_PAIR.get(symbol)
        if pair:
            pairs.append(pair)
        else:
            # Try generic conversion: BTCUSDT → BTC/USDT
            if symbol.endswith("USDT"):
                base = symbol[:-4]
                pairs.append(f"{base}/USDT")
            else:
                logger.warning("Cannot convert symbol %s to Freqtrade pair format", symbol)

    config: dict[str, Any] = {
        "max_open_trades": app_config.crypto.symbols.__len__(),
        "stake_currency": "USDT",
        "stake_amount": "unlimited",
        "tradable_balance_ratio": app_config.risk.max_position_fraction * 10,  # Scale up for Freqtrade
        "fiat_display_currency": "USD",
        "dry_run": dry_run,
        "dry_run_wallet": app_config.initial_cash,
        "cancel_open_orders_on_exit": True,

        "trading_mode": "spot",

        "exchange": {
            "name": exchange,
            "key": "",  # Never embed real keys in generated config
            "secret": "",
            "ccxt_sync_config": {
                "enableRateLimit": True,
            },
            "pair_whitelist": pairs,
            "pair_blacklist": [
                # Stablecoins and wrapped tokens
                "(BUSD|TUSD|USDC|DAI|PAX)/.*",
                ".*(DOWN|UP|BEAR|BULL)/.*",
            ],
        },

        "entry_pricing": {
            "price_side": "same",
            "use_order_book": True,
            "order_book_top": 1,
        },

        "exit_pricing": {
            "price_side": "same",
            "use_order_book": True,
            "order_book_top": 1,
        },

        "order_types": {
            "entry": "limit",
            "exit": "limit",
            "stoploss": "market",
            "stoploss_on_exchange": False,
        },

        "pairlists": [
            {
                "method": "StaticPairList",
            },
        ],

        # Stoploss maps to our kill switch drawdown
        "stoploss": -app_config.risk.kill_switch_drawdown,

        # Timeframe
        "timeframe": "1h",

        # Bot metadata
        "bot_name": "TradingBot-Freqtrade",
        "initial_state": "running",
        "force_entry_enable": False,

        # API server for dashboard (optional)
        "api_server": {
            "enabled": app_config.freqtrade.enabled,
            "listen_ip_address": "127.0.0.1",
            "listen_port": app_config.freqtrade.api_server_port,
            "verbosity": "error",
            "enable_openapi": False,
            "jwt_secret_key": "",  # Auto-generated by Freqtrade
            "CORS_origins": ["http://localhost:3000"],
            "username": "freqtrader",
            "password": "",  # Set via environment
        },

        # Internals
        "internals": {
            "process_throttle_secs": 5,
        },
    }

    if output_path:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(json.dumps(config, indent=2), encoding="utf-8")
        logger.info("Freqtrade config written to %s", output_path)

    return config


def generate_hyperopt_config(
    app_config: AppConfig,
    *,
    epochs: int = 100,
    spaces: list[str] | None = None,
    loss_function: str = "SharpeHyperOptLoss",
) -> dict[str, Any]:
    """Generate hyperopt-specific settings.

    Args:
        app_config: Our application config.
        epochs: Number of hyperopt epochs.
        spaces: Hyperopt search spaces (buy, sell, roi, stoploss, trailing).
        loss_function: Hyperopt loss function name.

    Returns:
        Hyperopt settings dict.
    """
    if spaces is None:
        spaces = ["buy", "sell", "roi", "stoploss", "trailing"]

    return {
        "epochs": epochs,
        "spaces": spaces,
        "loss_function": loss_function,
        "hyperopt_parameters": {
            "buy_rsi": {"low": 15, "high": 40, "default": 30, "space": "buy"},
            "sell_rsi": {"low": 60, "high": 85, "default": 70, "space": "sell"},
            "buy_volume_factor": {"low": 1.0, "high": 3.0, "default": 1.5, "space": "buy"},
            "rsi_period": {"low": 7, "high": 25, "default": 14, "space": "buy"},
        },
        "minimal_roi_ranges": {
            "0": {"low": 0.05, "high": 0.30},
            "60": {"low": 0.02, "high": 0.15},
            "120": {"low": 0.01, "high": 0.10},
            "360": {"low": 0.005, "high": 0.05},
        },
        "stoploss_range": {"low": -0.25, "high": -0.05},
    }
